def to_lines(rows, mode):
    out = []
    for label, value, h in rows:
        if label is None:
            out.append((value, h))
        elif value is None:
            out.append((label, h))
        elif mode == "merged":
            out.append((f"{label} {value}", h))
        else:
            out.append((label, h))
            out.append((value, h))
    return out


def ea(text):
    return extract_amount(text)


